#!/usr/bin/env python3
"""Check local source links/navigation without depending on external network availability."""
import json
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "sites/axvern-document-site/docs/en"
errors = []
checked = 0


def verify(source, url):
    global checked
    parsed = urlsplit(url)
    if parsed.scheme or parsed.netloc:
        return
    path = unquote(parsed.path)
    if not path:
        return  # same-page anchors are generated by the documentation engine
    if path.startswith("/"):
        target = SITE / path.lstrip("/")
    else:
        target = source.parent / path
    candidates = [target, target.with_suffix(".md"), target.with_suffix(".mdx"), target / "index.md", target / "index.mdx"]
    repository_directory = target.is_dir() and not target.resolve().is_relative_to(SITE)
    if not repository_directory and not any(p.is_file() for p in candidates):
        errors.append(f"{source.relative_to(ROOT)}: unresolved local link {url}")
    checked += 1


sources = [ROOT / "README.md", *SITE.rglob("*.md"), *SITE.rglob("*.mdx"), * (ROOT / "docs").rglob("*.md"), ROOT / "qualities/index.md"]
for source in sources:
    text = re.sub(r"```.*?```", "", source.read_text(), flags=re.S)
    for url in re.findall(r"!?\[[^\]]*\]\(([^\s)]+)(?:\s+[^)]*)?\)", text):
        verify(source, url)
for source in SITE.rglob("*.json"):
    def visit(value):
        if isinstance(value, dict):
            for key, item in value.items():
                if key == "link" and isinstance(item, str):
                    verify(source, item)
                else:
                    visit(item)
        elif isinstance(value, list):
            for item in value:
                visit(item)
    visit(json.loads(source.read_text()))
if errors:
    raise SystemExit("\n".join(errors))
print(f"local documentation links: {checked} checked")
